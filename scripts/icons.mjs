#!/usr/bin/env node
// Writes src/components/ui/icons.gen.ts: the SVG of every icon the interface
// uses, taken from the Phosphor set (@iconify-json/ph, MIT). Icons are part
// of the built pages: nothing is fetched at run time.
//
// Regular weight for the interface, duotone for identity logos. Run it after
// changing either list: `pnpm icons`. The output is committed.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(
  await readFile(require.resolve("@iconify-json/ph/icons.json"), "utf8"),
);

/** Icons of the interface itself. */
const UI = [
  "arrow-left",
  "arrow-square-out",
  "check",
  "check-circle",
  "copy",
  "download-simple",
  "fingerprint",
  "identification-card",
  "info",
  "key",
  "moon",
  "pencil-simple",
  "plus",
  "sign-out",
  "sun",
  "translate",
  "trash",
  "warning",
  "warning-circle",
  "x",
];

// The logo library is the list the picker offers.
const library = await readFile(
  new URL("../src/lib/icons.ts", import.meta.url),
  "utf8",
);
const LOGOS = [
  ...library
    .slice(library.indexOf("ICON_GROUPS"), library.indexOf("LOGO_NAMES"))
    .matchAll(/^\s+"([a-z0-9-]+)",$/gm),
].map((m) => m[1]);
if (LOGOS.length === 0) throw new Error("no logo found in src/lib/icons.ts");

function body(name) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Phosphor has no icon named "${name}"`);
  return icon.body;
}

const entries = (names, suffix) =>
  names
    .toSorted()
    .map(
      (name) =>
        `  ${JSON.stringify(name)}:\n    ${JSON.stringify(body(name + suffix))},`,
    )
    .join("\n");

const out = `// Generated by scripts/icons.mjs from @iconify-json/ph. Do not edit.
// Phosphor Icons, MIT License: https://github.com/phosphor-icons/core

/** The size of every icon's drawing: \`viewBox="0 0 ${set.width} ${set.height}"\`. */
export const ICON_SIZE = ${set.width};

/** Regular weight: the interface. */
export const UI_ICONS = {
${entries(UI, "")}
} as const;

/** Duotone weight: the logos of identities. */
export const LOGO_ICONS: Record<string, string> = {
${entries(LOGOS, "-duotone")}
};
`;
await writeFile(
  new URL("../src/components/ui/icons.gen.ts", import.meta.url),
  out,
);
console.log(
  `icons.gen.ts: ${UI.length} interface icons, ${LOGOS.length} logos`,
);
